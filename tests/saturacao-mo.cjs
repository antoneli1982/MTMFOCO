const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ctx = {window:{},document:{addEventListener(){}}};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname,'../planejamento.js'),'utf8'), ctx);
const calc = (dedicacoes, takt=1800, extra=[]) => ctx.window.planRecursosCalc({takt,recursos:dedicacoes.map(dedicacao=>({tipo:'operador',dedicacao})).concat(extra)},2629.66);
assert.equal(calc([100,100,100]).saturacaoMO.toFixed(1),'48.7');
assert.equal(calc([100,100]).saturacaoMO.toFixed(1),'73.0');
assert.equal(calc([100,50]).saturacaoMO.toFixed(1),'97.4');
assert.equal(calc([100]).saturacaoMO.toFixed(1),'146.1');
assert.equal(calc([100,100],1800,[{tipo:'maquina',dedicacao:100}]).saturacaoMO,calc([100,100]).saturacaoMO);
assert.equal(calc([]).saturacaoMO,null);
assert.equal(calc([0,0]).saturacaoMO,null);
assert.equal(calc([100],0).saturacaoMO,null);
assert.equal(calc([100],-1).saturacaoMO,null);
assert.equal(calc([-10,200,'abc']).fatorMO,1);
assert.ok(calc([100]).saldoMO < 0);
assert.ok(calc([100,100]).saldoMO > 0);
console.log('12 verificações de saturação da mão de obra aprovadas.');
const heads = calc([100,50,0]).saturacaoHeads;
assert.equal(heads.heads.length,3);
assert.equal(heads.heads[2].percentual,null);
assert.equal(heads.heads[0].carga,heads.heads[1].carga*2);
assert.equal(heads.heads[0].percentual,heads.heads[1].percentual);
assert.ok(Math.abs(heads.heads.reduce((s,h)=>s+h.carga,0)-2629.66)<1e-9);
assert.ok(Math.abs(heads.heads.reduce((s,h)=>s+h.saldo,0)-heads.saldo)<1e-9);
assert.equal(calc([100],0).saturacaoHeads,null);
assert.equal(calc([0]).saturacaoHeads,null);
assert.equal(calc([100],1800,[{tipo:'maquina',dedicacao:100}]).saturacaoHeads.heads.length,1);
assert.ok(calc([100]).saturacaoHeads.heads[0].saldo<0);
console.log('10 verificações de saturação global e por head aprovadas.');
