vm.createContext(ctx);
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname,'../planejamento.js'),'utf8'),ctx);
const calc = ctx.window.planOcupacaoCalc;
const pos = (extra={}) => Object.assign({posicao:'P1',turno:'T1',capacidadeSeg:3600,atividades:{a:30}},extra);
